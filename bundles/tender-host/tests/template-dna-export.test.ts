import assert from 'node:assert/strict'
import { test } from 'node:test'
import { inspectOfficeZip } from '../src/deliverable-format.ts'
import { inspectTemplateDocx, type TemplateDocxFormat } from '../src/template-dna-office.ts'
import { createDocxBuffer, createMarkdownHtml, exportPreparedMarkdown } from '../src/export-document.ts'
import { prepareTemplateExport } from '../src/template-dna-export.ts'

const markdown = '# 项目报告\n\n当前项目事实来自已登记资料。\n\n| 阶段 | 内容 |\n| --- | --- |\n| 准备 | 当前项目实施工作 |\n'
const native: TemplateDocxFormat = {
  page: { widthTwips: 23811, heightTwips: 16838, orientation: 'landscape', marginTopTwips: 1000, marginRightTwips: 1200, marginBottomTwips: 1300, marginLeftTwips: 1400 },
  body: { fontFamily: 'Times New Roman', eastAsiaFontFamily: '仿宋', fontSizePt: 14, spacingBeforeTwips: 0, spacingAfterTwips: 80, lineSpacing: 360, lineRule: 'auto', alignment: 'both' },
  headingStyles: [{ styleId: 'SourceTitle', level: 1, fontFamily: 'Arial', eastAsiaFontFamily: '黑体', fontSizePt: 18, bold: true, spacingBeforeTwips: 200, spacingAfterTwips: 160, alignment: 'center' }],
  numbering: [], tables: [{ headers: ['阶段', '内容'], columnWidthsTwips: [1800, 5000], locator: 'source:table1' }],
  sectionCount: 1, headerFooter: { headers: 0, footers: 0, copySourceText: false }, warnings: [],
}

test('legacy exports retain their default fonts, pages, real ZIP and markdown behavior', () => {
  const file = exportPreparedMarkdown('report.md', markdown, 'docx')
  assert.equal(file.filename, 'report.docx'); assert.equal(file.templateWarnings, undefined)
  const document = inspectTemplateDocx(file.body)
  assert.equal(document.format.page?.widthTwips, 11906)
  assert.equal(document.format.body.fontFamily, 'Calibri'); assert.equal(document.format.body.fontSizePt, 11)
  assert.equal(exportPreparedMarkdown('report.md', markdown, 'md').body.toString(), markdown)
  assert.match(createMarkdownHtml(markdown, 'Report'), /@page\{size:A4;margin:18mm 16mm;/)
})

test('real DOCX bytes apply observed page, margins, body and heading styles, spacing and exact table columns', () => {
  const before = JSON.stringify(native), output = exportPreparedMarkdown('report.md', markdown, 'docx', native)
  const actual = inspectTemplateDocx(output.body)
  assert.equal(JSON.stringify(native), before, 'the immutable source contract is not mutated')
  assert.deepEqual(actual.format.page, native.page)
  for (const [key, value] of Object.entries(native.body)) assert.equal((actual.format.body as any)[key], value, key)
  const heading = actual.format.headingStyles[0]!
  for (const [key, value] of Object.entries(native.headingStyles[0]!).filter(([key]) => key !== 'styleId')) assert.equal((heading as any)[key], value, key)
  assert.deepEqual(actual.format.tables[0]?.columnWidthsTwips, [1800, 5000])
  assert.match(actual.text, /当前项目事实/); assert.equal(output.templateWarnings?.length, 0)
  const xml = inspectOfficeZip(output.body).get('word/document.xml')!.toString()
  assert.match(xml, /<w:tblW w:w="6800" w:type="dxa"\/>/)
  assert.match(xml, /<w:tblLayout w:type="fixed"\/>/)
})

test('template HTML uses the same print dimensions, fonts, paragraph spacing and table width', () => {
  const output = exportPreparedMarkdown('report.md', markdown, 'html', native).body.toString()
  assert.match(output, /size:1190\.55pt 841\.9pt/)
  assert.match(output, /margin-top:50pt/); assert.match(output, /margin-left:70pt/)
  assert.match(output, /font-family:"Times New Roman","仿宋"/); assert.match(output, /font-size:14pt/)
  assert.match(output, /h1\{[^}]*font-size:18pt/)
  assert.match(output, /<table style="width:340pt;max-width:100%;table-layout:fixed"><colgroup><col style="width:90pt"><col style="width:250pt">/)
})

test('single-level ordered lists receive actual Word numbering definitions and bindings', () => {
  const format = { ...native, numbering: [{ id: 'old-id', levels: [{ level: 0, format: 'decimal', text: '%1)', start: 1 }] }] }
  const bytes = createDocxBuffer('# 项目报告\n\n1. 第一项\n2. 第二项\n', undefined, format)
  const files = inspectOfficeZip(bytes), content = files.get('word/document.xml')!.toString()
  assert.match(content, /<w:numPr><w:ilvl w:val="0"\/><w:numId w:val="1"\/><\/w:numPr>/)
  assert.equal(inspectTemplateDocx(bytes).format.numbering[0]?.levels[0]?.text, '%1)')
  assert.match(files.get('word/_rels/document.xml.rels')!.toString(), /relationships\/numbering/)
  assert.match(files.get('[Content_Types].xml')!.toString(), /word\/numbering.xml/)
})

test('unsafe font/CSS attributes, non-finite values and invalid page geometry never reach generated bytes', () => {
  for (const name of ['</style><script>alert(1)</script>', 'Arial; color:red', 'bad\u0000font']) {
    assert.throws(() => exportPreparedMarkdown('report.md', markdown, 'html', { ...native, body: { ...native.body, fontFamily: name } }), /字体/)
    assert.throws(() => createDocxBuffer(markdown, undefined, { ...native, body: { ...native.body, fontFamily: name } }), /字体/)
  }
  assert.throws(() => prepareTemplateExport({ ...native, body: { fontSizePt: NaN } }), /字号/)
  assert.throws(() => prepareTemplateExport({ ...native, body: { fontSizePt: 12.25 } }), /半磅/)
  assert.throws(() => prepareTemplateExport({ ...native, page: { ...native.page!, marginLeftTwips: 20000, marginRightTwips: 19000 } }), /占满纸张/)
  const escaped = inspectOfficeZip(createDocxBuffer(markdown, undefined, { ...native, body: { ...native.body, fontFamily: 'ACME & Co' } })).get('word/styles.xml')!.toString()
  assert.match(escaped, /ACME &amp; Co/)
})

test('bound template PDF fails closed without a real HTML printer, while legacy fallback remains available', () => {
  const keys = ['PROGRAMFILES', 'PROGRAMFILES(X86)', 'LOCALAPPDATA'], saved = Object.fromEntries(keys.map(key => [key, process.env[key]]))
  try {
    for (const key of keys) delete process.env[key]
    assert.throws(() => exportPreparedMarkdown('report.md', markdown, 'pdf', native), /需要可用的 HTML 打印引擎/)
    const legacy = exportPreparedMarkdown('report.md', '# 普通 PDF\n正文。\n', 'pdf')
    assert.equal(legacy.body.subarray(0, 5).toString(), '%PDF-')
  } finally { for (const key of keys) if (saved[key] === undefined) delete process.env[key]; else process.env[key] = saved[key] }
})

test('complex sections/numbering remain visible review gaps instead of a claim of full fidelity', () => {
  const complex = { ...native, sectionCount: 2, numbering: [{ id: 'a', levels: [{ level: 0, format: 'decimal', text: '%1.' }, { level: 1, format: 'decimal', text: '%1.%2' }] }], warnings: ['多个分节仍需逐节复核。'] }
  const result = exportPreparedMarkdown('report.md', markdown, 'docx', complex)
  assert.ok(result.templateWarnings?.some(value => value.includes('分节')))
  assert.ok(result.templateWarnings?.some(value => value.includes('多级编号')))
})
